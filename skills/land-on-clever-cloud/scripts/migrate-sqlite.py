#!/usr/bin/env python3
"""migrate-sqlite.py — copy a SQLite database (an app's local file, never the repository's word) into the
PostgreSQL add-on, in ONE transaction, with a row-count proof per table.

Usage:
  python3 -I migrate-sqlite.py --sqlite FILE --pg-env-file FILE [--manifest FILE] [--dry-run] [--schema public]
  python3 -I migrate-sqlite.py --self-test

--sqlite FILE        the SQLite file copied from the machine that runs the app today (read only, opened
                     with mode=ro; data is never in git — the developer gives the path)
--pg-env-file FILE   KEY=VALUE file, mode 600, with POSTGRESQL_ADDON_HOST, _PORT, _DB, _USER, _PASSWORD
                     (written by `env-safe.sh env-file --addon <id> --only POSTGRESQL_ADDON_ --out FILE`,
                     never by hand from `clever addon env`): the password goes to a
                     PGPASSFILE (600, in a 700 temp folder), never on a command line
--dry-run            reads SQLite only: tables, translated schema, row counts; connects to nothing
Order: run it BEFORE the first deploy. If the app already started once and created its tables
(init_db), an EMPTY table that has every SQLite column is reused; a table with rows is refused.
--manifest FILE      proof (default .clever-landing/sqlite-manifest.json): per table, rows in SQLite and in
                     PostgreSQL after the copy, PASS only if every count is equal

What it does, in one psql --single-transaction run (ON_ERROR_STOP): CREATE TABLE for each table (types
by SQLite affinity: INTEGER PRIMARY KEY → bigint generated by default as identity, TEXT → text, REAL →
double precision, BLOB → bytea, other → numeric; NOT NULL and simple defaults kept; current_timestamp →
now()), COPY of every row (text format, escaped: tabs, newlines, backslashes, NULL, bytea hex), the
indexes declared in SQLite (simple CREATE [UNIQUE] INDEX statements), then setval() of each identity to
max(id). An existing table makes the whole run fail: nothing is half-copied. Then a count per table.
Foreign keys and triggers are not copied: listed in the manifest as to do by hand.

No value of the database or of the credentials is printed. Python 3 stdlib + psql. Exit: 0 PASS, 1 FAIL,
2 usage or configuration error.
"""
import argparse
import datetime
import json
import os
import re
import sqlite3
import stat
import subprocess
import sys
import tempfile

IDENT = re.compile(r"\A[A-Za-z_][A-Za-z0-9_]{0,62}\Z")
PG_KEYS = ("POSTGRESQL_ADDON_HOST", "POSTGRESQL_ADDON_PORT", "POSTGRESQL_ADDON_DB", "POSTGRESQL_ADDON_USER", "POSTGRESQL_ADDON_PASSWORD")


def qi(name):
    if not IDENT.match(name):
        raise SystemExit("refused: table or column name %r is not a plain identifier (rename it, or copy it by hand)" % name[:40])
    return '"%s"' % name


def pg_type(decl, is_pk_int):
    d = (decl or "").upper()
    if is_pk_int:
        return "bigint generated by default as identity"
    if "INT" in d:
        return "bigint"
    if any(k in d for k in ("CHAR", "CLOB", "TEXT")):
        return "text"
    if "BLOB" in d or not d:
        return "bytea" if "BLOB" in d else "text"
    if any(k in d for k in ("REAL", "FLOA", "DOUB")):
        return "double precision"
    if "BOOL" in d:
        return "boolean"
    return "numeric"


def pg_default(dflt):
    if dflt is None:
        return ""
    d = str(dflt).strip()
    if re.fullmatch(r"(?i)\(?current_timestamp\)?|\(?datetime\('now'\)\)?", d):
        return " default now()"
    if re.fullmatch(r"-?\d+(\.\d+)?|'[^']*'|(?i:null|true|false)", d):
        return " default " + d
    return ""          # an expression we do not translate: left out, listed in the manifest


def read_schema(conn):
    tables = []
    for (name, sql) in conn.execute("select name, sql from sqlite_master where type='table' and name not like 'sqlite_%' order by name"):
        cols = conn.execute("pragma table_info(%s)" % qi(name)).fetchall()      # cid, name, type, notnull, dflt, pk
        pks = [c for c in cols if c[5]]
        int_pk = len(pks) == 1 and "INT" in (pks[0][2] or "").upper()
        defs, todo = [], []
        for cid, cname, ctype, notnull, dflt, pk in cols:
            t = pg_type(ctype, int_pk and pk)
            dd = "" if (int_pk and pk) else pg_default(dflt)
            if dflt is not None and not dd and not (int_pk and pk):
                todo.append("default of %s.%s not translated" % (name, cname))
            defs.append("%s %s%s%s" % (qi(cname), t, " not null" if notnull and not pk else "", dd))
        if pks:
            defs.append("primary key (%s)" % ", ".join(qi(c[1]) for c in sorted(pks, key=lambda c: c[5])))
        if re.search(r"(?i)\breferences\b|\bforeign\s+key\b", sql or ""):
            todo.append("foreign keys of %s not copied (add them after the copy)" % name)
        n = conn.execute("select count(*) from %s" % qi(name)).fetchone()[0]
        tables.append({"name": name, "columns": [c[1] for c in cols], "blob": [c[1] for c in cols if "BLOB" in (c[2] or "").upper()],
                       "ddl": "create table %s (\n  %s\n);" % (qi(name), ",\n  ".join(defs)), "rows": n, "identity": pks[0][1] if int_pk else None, "todo": todo})
    indexes = []
    for (name, tbl, sql) in conn.execute("select name, tbl_name, sql from sqlite_master where type='index' and sql is not null order by name"):
        m = re.fullmatch(r"(?is)\s*create\s+(unique\s+)?index\s+(?:if\s+not\s+exists\s+)?([A-Za-z_]\w*)\s+on\s+([A-Za-z_]\w*)\s*\(([\w\s,]+)\)\s*", sql or "")
        if m:
            indexes.append("create %sindex %s on %s (%s);" % (m.group(1) or "", qi(m.group(2)), qi(m.group(3)), ", ".join(qi(c.strip()) for c in m.group(4).split(","))))
        else:
            indexes.append(None)
    return tables, indexes


def copy_value(v):
    if v is None:
        return "\\N"
    if isinstance(v, bytes):
        return "\\\\x" + v.hex()
    if isinstance(v, float) and v != v:
        return "NaN"
    s = str(v)
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r")


def write_script(conn, tables, indexes, schema, out, existing=()):
    out.write("set client_encoding = 'UTF8';\nset search_path = %s;\n" % qi(schema))
    for t in tables:
        if t["name"] not in existing:          # an EMPTY table already created by the app (init_db at start): reused
            out.write(t["ddl"] + "\n")
    for t in tables:
        cols = ", ".join(qi(c) for c in t["columns"])
        out.write("copy %s (%s) from stdin;\n" % (qi(t["name"]), cols))
        for row in conn.execute("select %s from %s" % (cols, qi(t["name"]))):
            out.write("\t".join(copy_value(v) for v in row) + "\n")
        out.write("\\.\n")
    for i in indexes:
        if i:
            out.write(re.sub(r"(?i)^create (unique )?index ", lambda m: "create %sindex if not exists " % (m.group(1) or ""), i) + "\n")
    for t in tables:
        if t["identity"]:
            out.write("select setval(pg_get_serial_sequence('%s', '%s'), coalesce(max(%s), 1), max(%s) is not null) from %s;\n" % (
                t["name"], t["identity"], qi(t["identity"]), qi(t["identity"]), qi(t["name"])))


def read_env_file(path):
    st = os.stat(path)
    if st.st_mode & (stat.S_IRWXG | stat.S_IRWXO):
        raise SystemExit("%s is readable by group/others: chmod 600 it first" % path)
    vals = {}
    for ln in open(path, encoding="utf-8"):
        m = re.match(r"^(?:export )?([A-Za-z_][A-Za-z0-9_]*)=(.*)$", ln.rstrip("\n"))
        if m:
            vals[m.group(1)] = m.group(2)          # as written by env-safe.sh env-file: no strip, no unquoting
    return vals


def pg_env(vals, tmp):
    missing = [k for k in PG_KEYS if not vals.get(k)]
    if missing:
        raise SystemExit("missing in the credentials file (names only): " + ", ".join(missing))
    pp = os.path.join(tmp, "pgpass")
    fd = os.open(pp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    esc = lambda x: x.replace("\\", "\\\\").replace(":", "\\:")  # noqa: E731
    with os.fdopen(fd, "w") as f:
        f.write("%s:%s:%s:%s:%s\n" % tuple(esc(vals[k]) for k in PG_KEYS))
    env = {k: v for k, v in os.environ.items() if not k.startswith("PG")}
    env.update({"PGHOST": vals["POSTGRESQL_ADDON_HOST"], "PGPORT": vals["POSTGRESQL_ADDON_PORT"], "PGDATABASE": vals["POSTGRESQL_ADDON_DB"],
                "PGUSER": vals["POSTGRESQL_ADDON_USER"], "PGPASSFILE": pp, "PGSSLMODE": "prefer" if vals["POSTGRESQL_ADDON_HOST"] in ("127.0.0.1", "localhost", "::1") else "require", "PGCONNECT_TIMEOUT": "20"})
    return env


def summarize_error(err):
    """A psql error may quote row data (DETAIL: Key (…)=(…), Failing row contains (…)): keep the SQLSTATE,
    the object names and the first line's message class only — never DETAIL nor a row."""
    code = re.search(r"(?:ERROR|FATAL|PANIC):\s+([0-9A-Z]{5}):", err)
    names = []
    for k in ("TABLE NAME", "COLUMN NAME", "CONSTRAINT NAME"):
        m = re.search(r"(?m)^%s:\s+([A-Za-z0-9_.]{1,63})\s*$" % k, err)
        if m:
            names.append("%s %s" % (k.split()[0].lower(), m.group(1)))
    rel = re.search(r'relation "([A-Za-z0-9_.]{1,63})" already exists', err)
    if rel:
        names.append("relation %s already exists" % rel.group(1))
    if not code:
        conn = re.search(r"(?i)(could not connect|connection to server|password authentication failed|timeout expired|SSL)", err)
        return "connection failed (%s)" % conn.group(1).lower() if conn else "psql failed (details withheld: they may contain row data)"
    return "ERROR %s%s (details withheld: they may contain row data)" % (code.group(1), (" — " + ", ".join(names)) if names else "")


def psql(env, args, timeout=3600):
    p = subprocess.run(["psql", "-X", "-q", "-v", "ON_ERROR_STOP=1", "-v", "VERBOSITY=verbose", "-v", "SHOW_CONTEXT=never"] + args,
                       env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=timeout)
    return p.returncode, p.stdout.decode("utf-8", "replace"), (summarize_error(p.stderr.decode("utf-8", "replace")) if p.returncode else "")


def self_test():
    ok = copy_value("a\tb\nc\\d\re") == "a\\tb\\nc\\\\d\\re" and copy_value(None) == "\\N" and copy_value(b"\x00\xff") == "\\\\x00ff"
    ok = ok and pg_type("INTEGER", True).startswith("bigint generated") and pg_type("varchar(20)", False) == "text" and pg_default("CURRENT_TIMESTAMP") == " default now()"
    print("COPY escaping and type mapping: %s" % ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sqlite")
    ap.add_argument("--pg-env-file")
    ap.add_argument("--manifest", default=os.path.join(".clever-landing", "sqlite-manifest.json"))
    ap.add_argument("--schema", default="public")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    if not a.sqlite or not os.path.isfile(a.sqlite) or (not a.dry_run and not a.pg_env_file):
        ap.print_usage()
        print("error: --sqlite FILE is required, and --pg-env-file FILE unless --dry-run")
        return 2
    qi(a.schema)
    conn = sqlite3.connect("file:%s?mode=ro" % os.path.abspath(a.sqlite), uri=True)
    tables, indexes = read_schema(conn)
    print("SQLite %s: %d table(s), %d row(s)" % (os.path.basename(a.sqlite), len(tables), sum(t["rows"] for t in tables)))
    for t in tables:
        print("  %-30s %8d rows%s" % (t["name"], t["rows"], ("  (identity %s)" % t["identity"]) if t["identity"] else ""))
    todo = [x for t in tables for x in t["todo"]] + ["an index not translated (copy it by hand)" for i in indexes if i is None]
    for x in todo:
        print("  TODO " + x)
    if a.dry_run:
        print("DRY RUN: nothing connected, nothing written. Schema that would be created:")
        for t in tables:
            print("\n".join("    " + ln for ln in t["ddl"].splitlines()))
        return 0
    vals = read_env_file(a.pg_env_file)
    old = os.umask(0o077)
    try:
        with tempfile.TemporaryDirectory(prefix="migrate-sqlite-") as tmp:
            env = pg_env(vals, tmp)
            # #22: the app may have created its tables at its first start (init_db): an EMPTY table with
            # every SQLite column is reused (data copied into it); a table with rows is refused.
            existing = []
            for t in tables:
                rc, out, err = psql(env, ["-At", "-c", "select case when to_regclass('%s.%s') is null then '-' else (select count(*)::text from %s.%s) end" % (
                    a.schema.replace("'", "''"), qi(t["name"]).replace("'", "''"), qi(a.schema), qi(t["name"]))], timeout=600)
                state = out.strip().splitlines()[-1] if rc == 0 and out.strip() else None
                if state is None:
                    rc, out, err = psql(env, ["-At", "-c", "select 1"], timeout=60)
                    if rc != 0:
                        print("FAIL  target unreachable: %s" % err.strip())
                        return 1
                    state = "-"
                if state == "-":
                    continue
                if state != "0":
                    print("REFUSED  %s already exists in the target with %s row(s): nothing copied (migrate BEFORE the first deploy, or empty it)" % (t["name"], state))
                    return 1
                rc, out, err = psql(env, ["-At", "-c", "select column_name from information_schema.columns where table_schema = '%s' and table_name = '%s'" % (
                    a.schema.replace("'", "''"), t["name"].replace("'", "''"))], timeout=600)
                have = set(out.split())
                lack = [c for c in t["columns"] if c not in have]
                if lack:
                    print("REFUSED  %s exists (empty) in the target but lacks column(s) %s: nothing copied" % (t["name"], ", ".join(lack)))
                    return 1
                existing.append(t["name"])
                print("  %s exists and is empty in the target (created by the app at start): reused, rows copied into it" % t["name"])
            script = os.path.join(tmp, "copy.sql")
            with open(script, "w", encoding="utf-8") as f:
                write_script(conn, tables, indexes, a.schema, f, existing)
            rc, _, err = psql(env, ["--single-transaction", "-f", script])
            if rc != 0:
                print("FAIL  the copy was rolled back (one transaction): %s" % err.strip())
                return 1
            results = []
            for t in tables:
                rc, out, err = psql(env, ["-At", "-c", "select count(*) from %s.%s" % (qi(a.schema), qi(t["name"]))], timeout=600)
                n = int(out.strip().splitlines()[-1]) if rc == 0 and out.strip() and out.strip().splitlines()[-1].isdigit() else None
                results.append({"table": t["name"], "sqlite": t["rows"], "postgresql": n, "status": "PASS" if n == t["rows"] else "FAIL"})
                print("%s  %-30s sqlite %d · postgresql %s" % (results[-1]["status"], t["name"], t["rows"], n))
    finally:
        os.umask(old)
    verdict = "PASS" if results and all(r["status"] == "PASS" for r in results) else "FAIL"
    doc = {"generated": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "tool": "migrate-sqlite.py",
           "source": os.path.basename(a.sqlite), "target": "%s:%s/%s" % (vals.get("POSTGRESQL_ADDON_HOST"), vals.get("POSTGRESQL_ADDON_PORT"), vals.get("POSTGRESQL_ADDON_DB")),
           "tables": results, "todo": todo, "verdict": verdict}
    if os.path.dirname(a.manifest):
        os.makedirs(os.path.dirname(a.manifest), exist_ok=True)
    with open(a.manifest, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1)
    print("VERDICT: %s — manifest %s" % (verdict, a.manifest))
    return 0 if verdict == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
