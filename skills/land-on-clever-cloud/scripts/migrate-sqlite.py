# R47: a value copied into a number or a character column must be stored as it is. PostgreSQL would otherwise change it without a word, under a PASS: a
# numeric(p,s) rounds it to its scale, a real or double precision keeps the nearest binary value (which prints back as another number), a varchar(n) or
# char(n) cuts trailing spaces beyond n, and a number column reads a TEXT value its own way (PostgreSQL 16+: a hexadecimal, octal or binary prefix, an
# underscore between digits; any version: a space around it). Checked on the value exactly as copy_value renders it; refused, never rewritten
PLAIN_NUMBER = re.compile(r"[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?", re.ASCII)      # fullmatch only: ASCII digits, no space, no _, no prefix
NUMBER_WORD = re.compile(r"(?i:nan|[+-]?inf(?:inity)?)", re.ASCII)          # what numeric and the float types both read as itself, in any case
FLOAT_BITS = {"real": 24, "double precision": 53}
FLOAT_RANGE = {24: (-149, 127), 53: (-1074, 1023)}          # significand bits: (exponent of the smallest subnormal, largest exponent)
COERCE_FIX = "fix it in your app or your own script, or change the column in the app's migrations, then rerun"
COERCE_FIX_NEW = "fix it in your app or your own script, then rerun"          # a column this script creates
COERCE_WHY = {
    "form": "are text that is not a plain decimal number (a space around it, an underscore between digits, a hexadecimal, octal or binary prefix, a word) "
            "and the column is %s in PostgreSQL, which would read them its own way",
    "scale": "carry non-zero digits beyond the scale of the column, %s in PostgreSQL, which would round them",
    "float": "are not kept as they are by the column, %s in PostgreSQL: it would store the nearest binary value, which prints back as another number",
    "length": "are longer than the column, %s in PostgreSQL, allows: it would cut their trailing spaces, or refuse them",
}


def column_spec(typ):
    """What a column type keeps (R47), as format_type renders it (domains read through to their base type): ("int", None) for smallint, integer, bigint;
    ("numeric", its scale, None when unconstrained); ("float", 24 or 53 significand bits) for real, double precision; ("chars", n) for varchar(n), char(n);
    None for any other type (text, an unbounded varchar, a date, an array…)."""
    if typ in ("smallint", "integer", "bigint"):
        return "int", None
    if typ in FLOAT_BITS:
        return "float", FLOAT_BITS[typ]
    m = re.fullmatch(r"numeric(?:\((\d+)(?:,(-?\d+))?\))?", typ or "", re.ASCII)
    if m:
        return "numeric", (int(m.group(2) or 0) if m.group(1) else None)
    m = re.fullmatch(r"(?:character varying|character)\((\d+)\)", typ or "", re.ASCII)
    return ("chars", int(m.group(1))) if m else None


def beyond_scale(text, scale):
    """Whether the plain decimal `text` has a non-zero digit beyond `scale` (negative: left of the point), which numeric(p, scale) would round away."""
    try:
        _, digits, exp = decimal.Decimal(text).as_tuple()
    except decimal.InvalidOperation:          # an exponent beyond Decimal's range: never stored as it is
        return True
    sig = "".join(map(str, digits)).rstrip("0")
    return bool(sig) and exp + len(digits) - len(sig) < -scale          # the exponent of its last non-zero digit


def float_print(d, bits):
    """PostgreSQL 12+'s output of the finite Decimal d read into real (bits 24) or double precision (53), as a Decimal: d rounded to the nearest binary
    value (ties to even), then the shortest decimal strictly inside that value's rounding interval — its bounds excluded, unlike Python's repr —, the
    nearest of them when several. None when the value is out of the type's range (PostgreSQL refuses it). Exact rational arithmetic; checked against
    PostgreSQL 17 on 60,000 values for both types."""
    if not d:
        return decimal.Decimal(0)
    q = abs(fractions.Fraction(d))
    emin, emax = FLOAT_RANGE[bits]
    e = q.numerator.bit_length() - q.denominator.bit_length()
    if fractions.Fraction(2) ** e > q:
        e -= 1
    u = max(e - bits + 1, emin)
    m, r = divmod(q / fractions.Fraction(2) ** u, 1)
    m = int(m) + (1 if r > fractions.Fraction(1, 2) or (r == fractions.Fraction(1, 2) and m % 2) else 0)
    if m == 2 ** bits:
        m, u = m // 2, u + 1
    if not m or u > emax - bits + 1:
        return None
    x = m * fractions.Fraction(2) ** u
    below = fractions.Fraction(2) ** (u - 1) if m == 2 ** (bits - 1) and u > emin else fractions.Fraction(2) ** u
    lo, hi = x - below / 2, x + fractions.Fraction(2) ** u / 2
    p = len(str(x.numerator // x.denominator)) - 1 if x >= 1 else -len(str(x.denominator // x.numerator))
    while fractions.Fraction(10) ** p > x:
        p -= 1
    while fractions.Fraction(10) ** (p + 1) <= x:
        p += 1
    for n in range(1, 18):
        unit = fractions.Fraction(10) ** (p - n + 1)
        klo, khi = math.floor(lo / unit) + 1, math.ceil(hi / unit) - 1
        if klo <= khi:
            f = math.floor(x / unit)
            k = min((k for k in (f, f + 1) if klo <= k <= khi), key=lambda k: (abs(k * unit - x), k % 2))
            out = decimal.Decimal(k).scaleb(p - n + 1)
            return -out if d < 0 else out
    return None


def float_kept(text, bits):
    """Whether the plain decimal `text`, read into real (24) or double precision (53), prints back as the same number (the resolved criterion: the exact
    decimal of the source against the exact decimal PostgreSQL prints)."""
    try:
        sign, digits, exp = decimal.Decimal(text).as_tuple()
    except decimal.InvalidOperation:
        return False
    ds = "".join(map(str, digits))
    sig = ds.rstrip("0")
    exp += len(ds) - len(sig)          # the value is ±sig × 10^exp, sig without trailing zeros
    sig = sig.lstrip("0")
    if not sig:
        return True                           # a zero: 0, -0 (printed -0)
    if len(sig) > (9 if bits == 24 else 17) or not -400 < exp + len(sig) - 1 < 400:
        return False                          # more digits than PostgreSQL ever prints for that type, or out of its range
    if exp >= 0 and int(sig) * 10 ** exp <= 2 ** bits:
        return True                           # an integer the type holds exactly, printed as it is
    return printed_same(sign, int(sig), exp, bits)


@functools.lru_cache(maxsize=65536)
def printed_same(sign, sig, exp, bits):
    """float_kept's exact case, cached (a column repeats its values): the decimal (-1)^sign × sig × 10^exp, at most 17 digits."""
    d = decimal.Decimal((sign, tuple(int(x) for x in str(sig)), exp))
    return float_print(d, bits) == d


def changed_how(spec, v):
    """How PostgreSQL would store the value v (as copy_value renders it) differently in a column `spec` (column_spec) — "form", "scale", "float", "length" —
    or None when it keeps it as it is. A fraction or an out-of-range value into an integer column, Infinity into a numeric(p,s): PostgreSQL refuses them
    itself, loudly (the copy rolls back)."""
    if v is None or isinstance(v, bytes):          # blobs: blob_refusals; invalid UTF-8: value_refusals
        return None
    kind, n = spec
    if kind == "chars":
        return "length" if len(v if isinstance(v, str) else "NaN" if v != v else str(v)) > n else None
    if isinstance(v, str) and not PLAIN_NUMBER.fullmatch(v):
        return None if kind != "int" and NUMBER_WORD.fullmatch(v) else "form"
    if kind == "int" or (kind == "numeric" and n is None) or (kind == "float" and n == 53 and isinstance(v, float)):
        return None          # an unconstrained numeric keeps any decimal; a SQLite REAL is a double, which double precision stores bit for bit
    text = v if isinstance(v, str) else "NaN" if v != v else str(v)
    if NUMBER_WORD.fullmatch(text):
        return None
    if kind == "numeric":
        return "scale" if beyond_scale(text, n) else None
    return None if float_kept(text, n) else "float"


def coerce_refusals(conn, t, types, fix=COERCE_FIX):
    """R47: one streaming pass (numbered) over the columns of t that the target's types (`types`) concern — none: no pass —, for the values PostgreSQL would
    store differently (changed_how). One line per column and kind: table.column, how many, the column's type, one row id, never the value."""
    specs = {c: column_spec(types.get(c)) for c in t["columns"]}
    # an integer column, or an unconstrained numeric, changes only a TEXT value: a source column without one (value_refusals noted them) needs no pass
    cols = [c for c in t["columns"] if specs[c] and (specs[c] not in (("int", None), ("numeric", None)) or c in t.get("texts", t["columns"]))]
    if not cols:
        return []
    found = {}
    for r in numbered(conn, t["name"], ", ".join(qi(c) for c in cols)):
        for c, v in zip(cols, r[1:]):
            how = changed_how(specs[c], v)
            if how:
                found.setdefault((c, how), [0, r[0]])[0] += 1
    return coerce_lines(t, found, types, fix)


def coerce_lines(t, found, types, fix):
    """The refusal lines of coerce_refusals and value_refusals, in column order: found {(column, kind): [count, row id]}."""
    return ["REFUSED  %s.%s: %d value(s) %s (e.g. %s) — nothing copied: %s" % (t["name"], c, found[(c, how)][0], COERCE_WHY[how] % types[c], found[(c, how)][1], fix)
            for c in t["columns"] for how in ("form", "scale", "float", "length") if (c, how) in found]


def schema_refusal(conn):
    """R46: the schema's own text — a table's name or SQL, a column's name, type or default, an index's or a trigger's SQL — must be valid UTF-8, else the
    run is refused before anything is read, the table named by its position in the file (its name too when it is a plain identifier), never the bytes."""
    rows = conn.execute("select type, name, tbl_name, sql from sqlite_master order by rowid").fetchall()
    pos = {}
    for typ, name, tbl, sql in rows:
        if typ == "table" and not (isinstance(name, str) and name.startswith("sqlite_")):
            pos[name] = len(pos) + 1

    def where(key):
        n = pos.get(key)
        return ("table #%d%s" % (n, " (%s)" % key if isinstance(key, str) and IDENT.match(key) else "")) if n else "a view, index or trigger of the file"
    found = next((tbl if tbl in pos else name for typ, name, tbl, sql in rows if any(isinstance(x, BadText) for x in (typ, name, tbl, sql))), None)
    if found is None:
        for key in [k for k in pos if isinstance(k, str)]:
            if any(isinstance(x, BadText) for c in conn.execute('pragma table_xinfo("%s")' % key.replace('"', '""')) for x in c):
                found = key
                break
    if found is None:
        return None
    return ("REFUSED  the schema of the file holds text that is not valid UTF-8: %s (its name, a column's name, type or default, or the SQL of the table, "
            "an index or a trigger on it; never shown) — nothing copied: fix it in your app or your own script (on a copy of the .db), then rerun" % where(found))


def form_of(typ, v):
    """The form of a value, never the value (R44: ASCII only): its SQLite type for a number or a blob; for text, its first 40 characters with each ASCII digit
    as 9, each ASCII letter as a — a T or a Z right after a digit kept (a date-time separator, a zone) —, - : . + / and the space kept, and EVERY other
    character as ? (an accented letter, CJK, Cyrillic, a newline, ESC, a bidi mark, a non-ASCII digit): no fragment of the value, no line it could forge."""
    if typ != "text":
        return typ
    out = []
    for i, ch in enumerate(v[:40]):
        if "0" <= ch <= "9":
            out.append("9")
        elif ch in "TZ" and i and "0" <= v[i - 1] <= "9":
            out.append(ch)
        elif "a" <= ch <= "z" or "A" <= ch <= "Z":
            out.append("a")
        elif ch in "-:.+/ ":
            out.append(ch)
        else:
            out.append("?")
    return "".join(out)


def ms_text(v):
    """Ruling R44: integer epoch milliseconds → the exact UTC timestamp(3) text, in integer arithmetic (no float): 1698765432123 → '2023-10-31 15:17:12.123'."""
    s, ms = divmod(int(v), 1000)
    return (datetime.datetime(1970, 1, 1) + datetime.timedelta(seconds=s)).strftime("%Y-%m-%d %H:%M:%S") + ".%03d" % ms


def clock_ok(h, mi, s, f=None):
    """(valid, at 24:00) of a time of day: hours 0-23, or 24:00[:00[.000]] exactly (PostgreSQL reads it as 00:00 of the next day, the same instant)."""
    h, mi, s = int(h), int(mi), int(s or 0)
    if h == 24:
        return (mi == 0 and s == 0 and not (f or "").strip("0")), True
    return (h < 24 and mi < 60 and s < 60), False


def time_inspect(conn, table, col):
    """What the values of one SQLite column are, as a date or a time (counts, one example rowid and one form per kind — never a value): "number", "blob",
    "other" (no form this script reads), "invalid" (2024-02-30, 25:00, an offset beyond ±15:59), "timeonly" (HH:MM[:SS]), "naive" / "utc" / "offset" (a
    date-time or a date: without an offset, Z or ±00:00, another offset), "has_time" (a time part), "clock" (a time of day or a non-UTC offset a date would drop),
    "h24" (24:00), and "fracs" {digits: [count, rowid, form]} — the significant fractional digits (trailing zeros change nothing)."""
    k = dict.fromkeys(("n", "number", "integer", "int_ms", "blob", "badutf8", "other", "invalid", "timeonly", "naive", "utc", "offset", "has_time", "clock", "h24"), 0)
    k.update({"ex": {}, "form": {}, "fracs": {}})
    # R44 item 2, R45: the example is SQLite's own row id, never a user column (a generated one included), else the row's position in the table (numbered).
    # Item 7: the column is streamed, never loaded whole
    rows = ((rid, ty, v) for rid, ty, v in numbered(conn, table, "typeof(%s), %s" % (qi(col), qi(col))) if ty != "null")

    def mark(cat, rid, typ, v):
        k[cat] += 1
        k["ex"].setdefault(cat, rid)
        k["form"].setdefault(cat, form_of(typ, v))
    for rid, typ, v in rows:
        k["n"] += 1
        if typ in ("integer", "real"):
            mark("number", rid, typ, v)
            if typ == "integer":
                k["integer"] += 1
                k["int_ms"] += MS_RANGE[0] <= v <= MS_RANGE[1]
            continue
        if typ != "text":
            mark("blob", rid, typ, v)
            continue
        if isinstance(v, BadText):          # R45: not UTF-8 — never decoded, never shown (value_refusals refuses the run first)
            mark("badutf8", rid, "not UTF-8", v)
            continue
        m = TIME_ISO.match(v)
        mt = None if m else TIME_ONLY.match(v)
        if not m and not mt:
            mark("other", rid, typ, v)
            continue
        g = (m or mt).groupdict()
        ok, at24 = clock_ok(g["h"], g["mi"], g["s"], g.get("f")) if g.get("h") else (True, False)
        if m:
            try:
                datetime.date(int(g["y"]), int(g["mo"]), int(g["d"]))
            except ValueError:
                ok = False
            z = (g["z"] or "").strip()
            if z and z != "Z" and (int(z[1:3]) > 15 or int(z[4:6]) > 59):
                ok = False
        if not ok:
            mark("invalid", rid, typ, v)
            continue
        f = (g.get("f") or "").rstrip("0")
        if f:
            e = k["fracs"].setdefault(len(f), [0, rid, form_of(typ, v)])
            e[0] += 1
        if at24:
            mark("h24", rid, typ, v)
        if mt:
            mark("timeonly", rid, typ, v)
            continue
        z = (g["z"] or "").strip()
        mark("naive" if not z else "utc" if z == "Z" or not z.strip("+-0:") else "offset", rid, typ, v)
        if g["h"]:
            mark("has_time", rid, typ, v)
        clock = v[11:m.start("z")] if g["z"] else v[11:]
        if re.search(r"[1-9]", clock, re.ASCII) or (z and z != "Z" and z.strip("+-0:")):
            mark("clock", rid, typ, v)
    return k


def refusal(table, col, k, cat, why, n=None, ex=None, form=None, tail=None):
    """A refusal line (R43): table.column, how many values, why, the form found and one example rowid — never a value — and what to do."""
    return "REFUSED  %s.%s: %d value(s) %s (form found: %s, e.g. %s) — nothing copied: %s" % (
        table, col, k[cat] if n is None else n, why, k["form"][cat] if form is None else form, k["ex"][cat] if ex is None else ex, tail or CONVERT)


def frac_refusal(table, col, k, keep, kind):
    """More significant fractional digits than the column keeps: PostgreSQL would round them (.123456 into timestamp(3), .5 into timestamp(0))."""
    over = sorted((d, e) for d, e in k["fracs"].items() if d > keep)
    if not over:
        return None
    return refusal(table, col, k, None, "carry more than %d fractional digits of a second (up to %d) and the column keeps %d (%s): PostgreSQL would round them" % (
        keep, over[-1][0], keep, kind), n=sum(e[0] for _, e in over), ex=over[0][1][1], form=over[0][1][2])


def base_refusal(table, col, k, time_column=False):
    """What no date or time column takes: numbers, blobs, forms this script does not read, invalid dates or times (and a bare time of day outside a time column)."""
    for cat, why in (("number", NUMBER_WHY), ("blob", "are blobs, not dates"), ("badutf8", "are not valid UTF-8 text"), ("other", FORM_WHY), ("invalid", INVALID_WHY)):
        if k[cat]:
            return refusal(table, col, k, cat, why)
    if k["timeonly"] and not time_column:
        return refusal(table, col, k, "timeonly", "are a time of day without a date")
    return None


def time_notes(table, col, kind, k):
    """The lines that say how a value is read without being changed (R43 item 7, R42): values without an offset into timestamptz are UTC (the copy runs with
    timezone UTC), whatever the SQLite column's declared type; 24:00 is 00:00 of the next day, the same instant."""
    out = []
    if kind == "timestamptz" and k["naive"]:
        out.append("  NOTE %s.%s: %d value(s) without an offset go into timestamptz: read as UTC (the copy runs with timezone UTC; '2024-01-02 01:04:05' is "
                   "01:04:05 UTC)" % (table, col, k["naive"]))
    if kind == "timetz" and k["timeonly"]:          # R44 item 8: a time of day without an offset into timetz is stored at +00
        out.append("  NOTE %s.%s: %d value(s) without an offset go into timetz: read as UTC (stored +00; the copy runs with timezone UTC)" % (table, col, k["timeonly"]))
    if kind in ("timestamp", "timestamptz") and k["h24"]:
        out.append("  NOTE %s.%s: %d value(s) at 24:00: PostgreSQL reads them as 00:00 of the next day, the same instant" % (table, col, k["h24"]))
    return out


def fresh_check(table, col, decl, k):
    """(the PostgreSQL type of a new column declared DATETIME / TIMESTAMP / DATE, a refusal or None, notes): what this script creates must hold every value as
    it is — a date column only plain dates (else the date statement), a timestamp column no offset (an offset → timestamptz; non-UTC offsets next to values
    without one: refused, whether those are UTC cannot be decided; Z or ±00:00 next to them: timestamptz, read as UTC, said), at most 6 fractional digits."""
    if decl == "time":          # R44 item 6: a TIME column (Django's TimeField): times of day only, as they are
        r = target_check(table, col, "time", 6, k)[0]
        return decl, r, []
    r = base_refusal(table, col, k)
    if r:
        return decl, r, []
    if decl == "date":
        if k["has_time"]:
            return decl, refusal(table, col, k, "has_time", "are not a plain date (YYYY-MM-DD): date would drop their time part",
                                 tail="keep the written date only (%s), or %s" % (remedy_date(table, col), CONVERT)), []
        return decl, None, []
    if k["offset"] and k["naive"]:
        return decl, refusal(table, col, k, "offset", "carry a non-UTC offset next to %d value(s) without one: whether those are UTC cannot be decided" % k["naive"]), []
    r = frac_refusal(table, col, k, 6, "a new timestamp keeps 6")
    if r:
        return decl, r, []
    kind = "timestamptz" if k["utc"] + k["offset"] else "timestamp"
    return kind, None, time_notes(table, col, kind, k)


def target_check(table, col, kind, prec, k, prisma=False):
    """(a refusal or None, notes) INTO an existing column of PostgreSQL type `kind` (timestamp, timestamptz, date, time) and fractional precision `prec`: a
    timestamp refuses a non-UTC offset (dropped; Z and ±00:00 are UTC), a date a time of day or a non-UTC offset (the date statement), a time a date-time (the
    date dropped), each more fractional digits than it keeps; any SQLite column, whatever its declared type (TEXT, untyped, DATETIME).
    Ruling R44 (the one conversion): into a timestamp(3) of a database Prisma created (`prisma`: it holds _prisma_migrations), a column that holds ONLY
    integers, all within [1e11, 1e14], is read as epoch milliseconds [assumed: Prisma's SQLite encoding] and copied exactly as UTC (k["convert"]; ms_text);
    anything else in it — a real, a value out of that range, a text next to them — stays refused."""
    if (prisma and kind == "timestamp" and prec is not None and int(prec) == 3 and k["number"] and k["number"] == k["n"]
            and k["integer"] == k["number"] and k["int_ms"] == k["number"]):
        k["convert"] = "epoch_ms"
        return None, ["  NOTE %s.%s: %d value(s) %s, copied as their exact UTC timestamp(3) (the .db is not changed)" % (table, col, k["number"], MS_NOTE)]
    r = base_refusal(table, col, k, time_column=(kind in ("time", "timetz")))
    if r:
        return r, []
    if kind in ("time", "timetz") and k["naive"] + k["utc"] + k["offset"]:
        cat = next(c for c in ("naive", "utc", "offset") if k[c])
        return refusal(table, col, k, cat, "carry a date and the target column is %s, which drops it" % kind, n=k["naive"] + k["utc"] + k["offset"]), []
    if kind == "date":
        if k["clock"]:
            return refusal(table, col, k, "clock", "carry a time of day or a non-UTC offset and the target column is date, which drops them",
                           tail="keep the written date only (%s), or make the column a timestamp in the app's migrations (Prisma: no @db.Date), or %s" % (
                               remedy_date(table, col), CONVERT)), []
        return None, []
    if kind == "timestamp" and k["offset"]:
        return refusal(table, col, k, "offset", "carry a non-UTC offset (+hh:mm / -hh:mm) and the target column is timestamp without time zone, which drops it "
                       "(03:04:05+02:00 stored as 03:04:05; or make it timestamptz in the app's migrations, Prisma: @db.Timestamptz)"), []
    r = frac_refusal(table, col, k, 6 if prec is None else int(prec), "%s(%s)" % (kind, 6 if prec is None else prec))
    return (r, []) if r else (None, time_notes(table, col, kind, k))


def qi(name):
    if not IDENT.match(name):
        raise SystemExit("refused: table or column name %r is not a plain identifier (rename it, or copy it by hand)" % name[:40])
    return '"%s"' % name


def pg_type(decl, is_pk_int):
    d = (decl or "").upper()
    if is_pk_int:
        return "bigint generated by default as identity"
    if "DATETIME" in d or "TIMESTAMP" in d:          # SQLite's text timestamps ('2024-01-02 03:04:05'): numeric would refuse them; timestamptz: read_schema
        return "timestamp"
    if re.search(r"\bDATE\b", d, re.ASCII):                   # '2024-01-02': numeric refused it (22P02)
        return "date"
    if re.search(r"\bTIME\b", d, re.ASCII):                   # R44: Django's TimeField ('10:30:00'): numeric refused it (22P02)
        return "time"
    if "INT" in d:
        return "bigint"
    if any(k in d for k in ("CHAR", "CLOB", "TEXT")):
        return "text"
    if "BLOB" in d or not d:
        return "bytea" if "BLOB" in d else "text"
    if any(k in d for k in ("REAL", "FLOA", "DOUB")):
        return "double precision"
    # R47: Rails' t.json and Sequelize's JSON / UUID (NUMERIC affinity): numeric refused them (22P02). json keeps the text exactly (invalid JSON fails
    # loudly); a UUID stays text, which the uuid type would rewrite (case, braces, dashes)
    if "JSON" in d:
        return "json"
    if "UUID" in d:
        return "text"
    if "BOOL" in d:
        return "boolean"
    return "numeric"


BOOL_DEFAULTS = {"0": "false", "1": "true", "'0'": "false", "'1'": "true", "false": "false", "true": "true", "'false'": "false", "'true'": "true",
                 "'f'": "false", "'t'": "true", "null": "null"}


def pg_default(dflt, pgtype):
    """The PostgreSQL default of a column of type `pgtype`, or "" when SQLite's does not fit that type (dropped, listed in the manifest): CURRENT_TIMESTAMP →
    now() on a timestamp(tz) or text column only (numeric … default now() is ERROR 42804), CURRENT_DATE → current_date on a date, 0 / 1 → false / true on a
    boolean, a quoted literal on a timestamp(tz) or date, a number, a quoted literal or null elsewhere."""
    if dflt is None:
        return ""
    d = str(dflt).strip()
    if pgtype == "boolean":
        v = BOOL_DEFAULTS.get(d.lower())
        return (" default " + v) if v else ""
    if re.fullmatch(r"(?i)\(?current_timestamp\)?|\(?datetime\('now'\)\)?", d, re.ASCII):
        return " default now()" if pgtype in ("timestamp", "timestamptz", "text") else ""
    if re.fullmatch(r"(?i)\(?current_date\)?|\(?date\('now'\)\)?", d, re.ASCII):
        return " default current_date" if pgtype == "date" else ""
    if re.fullmatch(r"(?i)\(?current_time\)?", d, re.ASCII):
        return " default current_time" if pgtype == "time" else ""
    if pgtype in ("timestamp", "timestamptz", "date", "time"):
        return (" default " + d) if re.fullmatch(r"'[^']*'|(?i:null)", d, re.ASCII) else ""
    if re.fullmatch(r"'[^']*'|(?i:null)", d, re.ASCII) or (pgtype in ("bigint", "numeric", "double precision", "text") and re.fullmatch(r"-?\d+(\.\d+)?", d, re.ASCII)):
        return " default " + d
    return ""          # an expression we do not translate: left out, listed in the manifest


def read_schema(conn):
    tables = []
    # SQLite's own tables only (sqlite_sequence, sqlite_stat1…): a literal, case-sensitive prefix — LIKE 'sqlite_%' reads _ as a wildcard and ignores case,
    # which left sqliteusers and SQLiteBackup out without a word (R40)
    for (name, sql) in conn.execute("select name, sql from sqlite_master where type='table' and substr(name, 1, 7) <> 'sqlite_' and name <> ? order by name", (PRISMA_HISTORY,)):
        cols = conn.execute("pragma table_info(%s)" % qi(name)).fetchall()      # cid, name, type, notnull, dflt, pk
        pks = [c for c in cols if c[5]]
        int_pk = len(pks) == 1 and "INT" in (pks[0][2] or "").upper()
        defs, todo, refuse, forms, kinds, notes, types = [], [], [], {}, {}, [], {}
        for cid, cname, ctype, notnull, dflt, pk in cols:
            t = pg_type(ctype, int_pk and pk)
            if t in ("timestamp", "date", "time"):          # the values decide (R43): a new table holds each value as it is, or the copy is refused
                forms[cname] = time_inspect(conn, name, cname)
                kinds[cname] = t
                t, why, nts = fresh_check(name, cname, t, forms[cname])
                refuse += [why] if why else []
                notes += nts
            types[cname] = t.replace(" generated by default as identity", "")          # R46: what a blob would go into (blob_refusals)
            dd = "" if (int_pk and pk) else pg_default(dflt, t)
            if dflt is not None and not dd and not (int_pk and pk):
                todo.append("default of %s.%s not translated (dropped)" % (name, cname))
            defs.append("%s %s%s%s" % (qi(cname), t, " not null" if notnull and not pk else "", dd))
        if pks:
            defs.append("primary key (%s)" % ", ".join(qi(c[1]) for c in sorted(pks, key=lambda c: c[5])))
        if re.search(r"(?i)\breferences\b|\bforeign\s+key\b", sql or "", re.ASCII):
            todo.append("foreign keys of %s not copied (add them after the copy)" % name)
        n = conn.execute("select count(*) from %s" % qi(name)).fetchone()[0]
        tables.append({"name": name, "columns": [c[1] for c in cols], "blob": [c[1] for c in cols if "BLOB" in (c[2] or "").upper()],
                       "ddl": "create table %s (\n  %s\n);" % (qi(name), ",\n  ".join(defs)), "rows": n, "identity": pks[0][1] if int_pk else None, "todo": todo,
                       "refuse": refuse, "forms": forms, "kinds": kinds, "notes": notes, "types": types})
    indexes = []
    for (name, tbl, sql) in conn.execute("select name, tbl_name, sql from sqlite_master where type='index' and sql is not null order by name"):
        m = re.fullmatch(r"(?is)\s*create\s+(unique\s+)?index\s+(?:if\s+not\s+exists\s+)?([A-Za-z_]\w*)\s+on\s+([A-Za-z_]\w*)\s*\(([\w\s,]+)\)\s*", sql or "", re.ASCII)
        if m:
            indexes.append("create %sindex %s on %s (%s);" % (m.group(1) or "", qi(m.group(2)), qi(m.group(3)), ", ".join(qi(c.strip()) for c in m.group(4).split(","))))
        else:
            indexes.append(None)
    return tables, indexes


def copy_value(v):
    if v is None:
        return "\\N"
    if isinstance(v, BadText):          # R45: refused before (value_refusals); never copied as a blob, never printed
        raise ValueError("a TEXT value is not valid UTF-8")
    if isinstance(v, bytes):
        return "\\\\x" + v.hex()
    if isinstance(v, float) and v != v:
        return "NaN"
    s = str(v)
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r")


# R40: a table that already exists (created by the app, or by the first deploy's migrations: Prisma) carries its foreign keys, not deferrable, and the COPYs
# run in name order (Account and Post before User, a cycle): its keys are saved, dropped for the copy, then re-added as they were — pg_get_constraintdef keeps
# the actions, DEFERRABLE and NOT VALID — in the same transaction; re-adding validates them, so an orphan row rolls everything back
FK_SAVE = ("create temp table loc_fk on commit drop as select conrelid, conname, pg_get_constraintdef(oid) as def from pg_constraint "
           "where contype = 'f' and conrelid in (%s);\n"
           "do $loc$ declare r record; begin for r in select * from loc_fk order by conname loop "
           "execute format('alter table %%s drop constraint %%I', r.conrelid::regclass, r.conname); end loop; end $loc$;\n")
FK_RESTORE = ("do $loc$ declare r record; begin for r in select * from loc_fk order by conname loop "
              "execute format('alter table %s add constraint %I %s', r.conrelid::regclass, r.conname, r.def); end loop; end $loc$;\n")


def write_script(conn, tables, indexes, schema, out, existing=()):
    out.write("set client_encoding = 'UTF8';\nset search_path = %s;\n" % qi(schema))
    out.write("set timezone = 'UTC';\n")          # R42: a value without an offset into timestamptz is UTC, never the server's time zone
    for t in tables:
        if t["name"] not in existing:          # an EMPTY table already created by the app (init_db at start): reused
            out.write(t["ddl"] + "\n")
    if existing:
        out.write(FK_SAVE % ", ".join("'%s.%s'::regclass" % (qi(schema), qi(n)) for n in existing))
    for t in tables:
        cols = ", ".join(qi(c) for c in t["columns"])
        out.write("copy %s (%s) from stdin;\n" % (qi(t["name"]), cols))
        conv = [(t.get("convert") or {}).get(c) == "epoch_ms" for c in t["columns"]]      # R44: Prisma's epoch ms, checked by target_check
        # R46: a text value into a bytea column goes as the text's UTF-8 bytes (the text \x41 or a\b is no bytea escape)
        byt = [(t.get("types") or {}).get(c) == "bytea" for c in t["columns"]]
        for row in conn.execute("select %s from %s" % (cols, qi(t["name"]))):
            out.write("\t".join(copy_value(ms_text(v) if cv and v is not None else v.encode("utf-8") if bt and isinstance(v, str) else v)
                                for v, cv, bt in zip(row, conv, byt)) + "\n")
        out.write("\\.\n")
    if existing:
        out.write(FK_RESTORE)
    for t in tables:          # R42 (defence in depth): a column with a NULL in PostgreSQL where SQLite had a value fails the copy, in the same transaction
        cnt = ", ".join("count(%s)" % qi(c) for c in t["columns"])
        want = conn.execute("select %s from %s" % (cnt, qi(t["name"]))).fetchone()
        each = " ".join("if (select count(%s) from %s) <> %d then raise exception using errcode = 'LCN01', message = 'a NULL in PostgreSQL where SQLite "
                        "had a value', table = '%s', column = '%s'; end if;" % (qi(c), qi(t["name"]), w, t["name"], c) for c, w in zip(t["columns"], want))
        # no PL/pgSQL variable: a column of the same name would make it ambiguous (ERROR 42702)
        out.write("do $loc$ begin if (select row(%s) from %s) is distinct from row(%s) then %s end if; end $loc$;\n" % (
            cnt, qi(t["name"]), ", ".join("%d::bigint" % w for w in want), each))
