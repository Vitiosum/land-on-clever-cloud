def psql(env, args, timeout=3600):
    p = subprocess.run(["psql", "-X", "-q", "-v", "ON_ERROR_STOP=1", "-v", "VERBOSITY=verbose", "-v", "SHOW_CONTEXT=never"] + args,
                       env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=timeout)
    return p.returncode, p.stdout.decode("utf-8", "replace"), (summarize_error(p.stderr.decode("utf-8", "replace")) if p.returncode else "")


