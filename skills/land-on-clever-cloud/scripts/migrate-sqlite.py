class Interrupted(SystemExit):
    """SIGTERM, SIGHUP or SIGINT (once the handlers are in place), raised in the main thread wherever it stands, so every `with` and `finally` unwinds: the temporary folder (the PGPASSFILE and
    copy.sql) is removed, and subprocess.run kills a running psql, whose one transaction PostgreSQL then rolls back. Exit 128 + the signal number."""

    def __init__(self, signum):
        SystemExit.__init__(self, 128 + signum)
        self.signum = signum


CLEANUP_SIGNALS = (signal.SIGTERM, signal.SIGHUP, signal.SIGINT)


def _on_signal(signum, _frame):
    for s_ in CLEANUP_SIGNALS:          # from the first one on, SIGINT, SIGTERM and SIGHUP are ignored: a second Ctrl-C never cuts the clean-up short
        signal.signal(s_, signal.SIG_IGN)
    raise Interrupted(signum)


